"""Convert document text to static, inert Markdown blocks."""
from io import BytesIO
from html import escape
from zipfile import ZipFile
from xml.etree import ElementTree
import re
from urllib.parse import quote
from pathlib import Path

SECTIONS = ("schedule", "problems", "resources", "practice")
MARKER = "<!-- generated by scripts/documents.py -->"
WORD = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def plain(text):
    return "".join(c if c.isalnum() or c == " " else f"&#{ord(c)};" for c in text.strip())


def html_blocks(data):
    from bs4 import BeautifulSoup, NavigableString
    soup = BeautifulSoup(data, "html.parser")
    for noise in soup.select("script,style,nav,aside,footer,header,form,template,noscript,svg"):
        noise.decompose()
    root = soup.find("article") or soup.find("main") or soup.body or soup
    blocks = []
    buffer = []

    def flush(prefix=""):
        value = " ".join("".join(buffer).split())
        buffer.clear()
        if value:
            blocks.append((prefix, value))

    def walk(node):
        if isinstance(node, NavigableString):
            if type(node) is NavigableString:
                buffer.append(str(node))
            return
        name = node.name
        if name == "pre":
            flush()
            blocks.append(("code", node.get_text()))
            return
        boundary = name in ("div","section","p","li","br","tr","blockquote") or re.fullmatch("h[1-6]",name or "")
        if boundary:
            flush()
        for child in node.children:
            walk(child)
        if name in ("td","th"):
            buffer.append(" | ")
        if boundary:
            prefix = "- " if name == "li" else "### " if name.startswith("h") else ""
            flush(prefix)
    walk(root)
    flush()
    return blocks


def pdf_blocks(data):
    from pypdf import PdfReader
    reader = PdfReader(BytesIO(data))
    blocks = []
    for i, page in enumerate(reader.pages, 1):
        blocks.append(("### ", f"第 {i} 页"))
        text = page.extract_text() or ""
        if text.strip():
            blocks.extend(("", p) for p in re.split(r"\n\s*\n",text) if p.strip())
        else:
            blocks.append(("", "本页没有可提取的文字，请查看原文件。"))
    return blocks


def docx_blocks(data):
    with ZipFile(BytesIO(data)) as archive:
        xml = archive.read("word/document.xml")
    body = ElementTree.fromstring(xml).find(WORD+"body")
    blocks = []
    def paragraph(p):
        return "".join(node.text or "" if node.tag == WORD+"t" else " "
                       for node in p.iter() if node.tag in (WORD+"t",WORD+"tab",WORD+"br")).strip()
    for node in body:
        if node.tag == WORD+"p":
            value = paragraph(node)
            style = node.find("./"+WORD+"pPr/"+WORD+"pStyle")
            heading = style is not None and re.search(r"Heading|标题",style.get(WORD+"val",""),re.I)
            if value:
                blocks.append(("### " if heading else "",value))
        elif node.tag == WORD+"tbl":
            for row in node.findall(WORD+"tr"):
                cells = [" ".join(paragraph(p) for p in cell.iter(WORD+"p")) for cell in row.findall(WORD+"tc")]
                blocks.append(("", " | ".join(cells)))
    return blocks


def markdown(blocks):
    paragraphs = []
    for prefix, value in blocks:
        if prefix == "code":
            # Preserve indentation without interpreting backticks or Vue expressions.
            paragraphs.append("<pre><code v-pre>"+escape(value)+"</code></pre>")
        else:
            paragraphs.append(prefix + plain(" ".join(value.splitlines())))
    return "\n\n".join(paragraphs)


def import_uploads(root=Path(".")):
    for section in SECTIONS:
        directory = root / "docs" / section
        if not directory.exists():
            continue
        active = set()
        for source in sorted(directory.rglob("*")):
            fmt = source.suffix.lower()
            if not source.is_file() or fmt not in (".pdf",".docx",".txt"):
                continue
            output = source.with_name(source.name+".imported.md")
            if output.exists() and not output.read_text(encoding="utf8").startswith(MARKER):
                raise ValueError(f"输出文件名已被使用：{output}")
            data = source.read_bytes()
            if fmt == ".pdf":
                blocks = pdf_blocks(data)
            elif fmt == ".docx":
                blocks = docx_blocks(data)
            else:
                blocks = [("",p) for p in data.decode("utf-8-sig").splitlines() if p.strip()]
            link = "https://github.com/Narutomaki-0721/AMC.github.io/blob/main/"+quote(source.relative_to(root).as_posix())
            output.write_text(f"{MARKER}\n\n# {plain(source.stem)}\n\n[查看原文件]({link})\n\n"
                              +markdown(blocks or [("","没有可提取的文字，请查看原文件。")])+"\n",encoding="utf8")
            active.add(output)
        for stale in directory.rglob("*.imported.md"):
            if stale not in active and stale.read_text(encoding="utf8").startswith(MARKER):
                stale.unlink()


if __name__ == "__main__":
    import_uploads()
